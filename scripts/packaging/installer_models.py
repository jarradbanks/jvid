"""Generate Inno model definitions from the app's pinned Whisper model identities."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def definitions(source):
    revision = re.search(r'const REVISION: &str = "([0-9a-f]{40})";', source)
    models = re.findall(r'Model::(Base|Small|LargeV3Turbo) => \(\s*"([a-z0-9._-]+)",\s*'
                        r'([0-9_]+),\s*"([0-9a-f]{64})",\s*\)', source)
    if not revision or [m[0] for m in models] != ['Base', 'Small', 'LargeV3Turbo']:
        raise ValueError('Expected all three pinned app model identities; review the installer generator')
    if len({m[1] for m in models}) != len(models):
        raise ValueError('Installer model filenames must be unique')
    lines = ['; Generated by scripts/packaging/installer_models.py; do not edit.',
             '#define WhisperRevision "' + revision[1] + '"']
    for index, (_, filename, size, sha256) in enumerate(models):
        prefix = '#define Whisper' + str(index)
        byte_count = int(size.replace('_', ''))
        if not re.fullmatch(r'ggml-[a-z0-9_-]+\.bin', filename) or not 0 < byte_count < 2**63:
            raise ValueError('Expected a safe model filename and positive Int64 size')
        lines.extend([prefix + 'File "' + filename + '"', prefix + 'Size ' + str(byte_count),
                      prefix + 'MB ' + str((byte_count + 500_000) // 1_000_000),
                      prefix + 'SHA256 "' + sha256 + '"'])
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    source = (ROOT / 'crates/jvid-transcribe/src/models.rs').read_text()
    (ROOT / 'packaging/whisper-models.iss').write_text(definitions(source))
